import vm from 'node:vm';
import fs from 'node:fs';
import assert from 'node:assert/strict';

let Card;
const context = { HTMLElement: class {}, window: {}, console: { info() {} },
  customElements: { define(name, ctor) { if (name === 'van-power-flow-card') Card = ctor; } } };
vm.createContext(context);
vm.runInContext(fs.readFileSync(new URL('./van-power-flow-card.js', import.meta.url), 'utf8'), context);
const card = Object.create(Card.prototype);
card._wrap = { clientWidth: 600, clientHeight: 400 };
card._has = { battery: true, inverter: true };
card._center = node => node === 'battery' ? { x: 300, y: 300 } : { x: 300, y: 100 };
let reverse = true, active = true, writes = 0, html = '';
card._flow = () => ({ active, reverse });
card._svg = { setAttribute() {}, set innerHTML(value) { html = value; writes++; } };
card._draw();
assert.equal(writes, 1);
assert.equal((html.match(/<circle /g) || []).length, 3);
const begins = [...html.matchAll(/begin="([\d.-]+)s"/g)].map(m => Number(m[1]));
assert.equal(begins.length, 3);
assert.ok(begins.every(n => n <= 0), 'no particles wait at the origin');
assert.equal(new Set(begins).size, 3, 'particles start spaced along the path');
assert.equal((html.match(/<animateMotion path="M/g) || []).length, 3);
card._draw();
assert.equal(writes, 1, 'unchanged updates preserve the animation DOM');
reverse = false;
card._draw();
assert.equal(writes, 2, 'direction changes redraw');
card._wrap.clientWidth = 700;
card._draw();
assert.equal(writes, 3, 'resizes redraw');
active = false;
card._draw();
assert.equal(writes, 4);
assert.ok(!html.includes('<circle'), 'idle flows remove particles');
assert.equal(card._fmtGridState('grid'), 'Connected');
assert.equal(card._fmtGridState('not_connected'), 'Not Connected');
assert.equal(card._fmtGridState('unknown'), 'Unknown');
console.log('Flow timing, redraw, direction, resize, idle and grid-state checks passed');
